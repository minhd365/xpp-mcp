import * as fs from 'fs';
import * as path from 'path';
import { ModelInfo } from '../schemas/types';

/**
 * LabelManager — manages D365 label files.
 *
 * Each label requires TWO files:
 *   1. AxLabelFile descriptor XML  → ModelRoot/AxLabelFile/BBLabel_en-US.xml
 *   2. Label resource text file    → ModelRoot/AxLabelFile/LabelResources/en-US/BBLabel.en-US.label.txt
 *
 * Label ID format: @LabelFileId:LabelKey
 * e.g. @BBLabel:PersonCode
 */
export class LabelManager {
  constructor(
    private readonly packagesRoot: string,
    private readonly locale: string = 'en-US',
  ) {}

  /**
   * Derive a label file ID from a model name.
   * e.g. "BB" → "BBLabel"
   */
  getLabelFileId(modelName: string): string {
    return `${modelName}Label`;
  }

  /**
   * Build a label reference string.
   * e.g. ("BB", "PersonCode") → "@BBLabel:PersonCode"
   */
  buildRef(modelName: string, key: string): string {
    return `@${this.getLabelFileId(modelName)}:${key}`;
  }

  /**
   * Sanitize a label key: PascalCase, alphanumeric + underscore only.
   * e.g. "Person Code" → "PersonCode"
   * Returns undefined if the result would be empty (e.g. input was all digits/punctuation).
   */
  sanitizeKey(text: string): string | undefined {
    const key = text
      .split(/\s+/)
      .map(w => w.charAt(0).toUpperCase() + w.slice(1))
      .join('')
      .replace(/[^A-Za-z0-9_]/g, '');
    return key.length > 0 ? key : undefined;
  }

  /**
   * Upsert a label entry (add if missing, skip if already present).
   * Returns the label reference string, or the raw value if the key cannot be sanitized.
   */
  upsert(model: ModelInfo, key: string, value: string, comment?: string): string {
    const safeKey = this.sanitizeKey(key);
    if (!safeKey) {
      // Key is empty after sanitization (e.g. all-numeric input) — fall back to raw value
      console.error(`[LabelManager] Cannot create label key from "${key}" — using raw value`);
      return value;
    }

    const modelAotRoot = path.join(this.packagesRoot, model.packageFolder, model.name);
    const labelFileId = this.getLabelFileId(model.name);

    // Ensure directories exist
    const labelDir = path.join(modelAotRoot, 'AxLabelFile');
    const resourceDir = path.join(labelDir, 'LabelResources', this.locale);
    fs.mkdirSync(resourceDir, { recursive: true });

    // 1. Upsert the .label.txt resource file
    const txtPath = path.join(resourceDir, `${labelFileId}.${this.locale}.label.txt`);
    this.upsertTxtEntry(txtPath, safeKey, value, comment);

    // 2. Upsert the AxLabelFile descriptor XML
    const xmlName = `${labelFileId}_${this.locale}`;
    const xmlPath = path.join(labelDir, `${xmlName}.xml`);
    const relPath = `${model.name}\\${model.name}\\AxLabelFile\\LabelResources\\${this.locale}\\${labelFileId}.${this.locale}.label.txt`;
    this.upsertDescriptorXml(xmlPath, xmlName, labelFileId, this.locale, relPath);

    return this.buildRef(model.name, safeKey);
  }

  private upsertTxtEntry(txtPath: string, key: string, value: string, comment?: string): void {
    let content = fs.existsSync(txtPath) ? fs.readFileSync(txtPath, 'utf-8') : '';
    // Check if key already exists
    const keyPattern = new RegExp(`^${key}=`, 'm');
    if (keyPattern.test(content)) return; // already present

    const entry = `${key}=${value}\n ;${comment ?? 'Auto-generated by xpp-mcp'}\n`;
    content += entry;
    fs.writeFileSync(txtPath, content, 'utf-8');
  }

  private upsertDescriptorXml(
    xmlPath: string,
    xmlName: string,
    labelFileId: string,
    locale: string,
    relPath: string,
  ): void {
    if (fs.existsSync(xmlPath)) return; // already exists, no need to recreate

    const xml = [
      '<?xml version="1.0" encoding="utf-8"?>',
      '<AxLabelFile xmlns:i="http://www.w3.org/2001/XMLSchema-instance">',
      `\t<Name>${xmlName}</Name>`,
      `\t<LabelContentFileName>${labelFileId}.${locale}.label.txt</LabelContentFileName>`,
      `\t<LabelFileId>${labelFileId}</LabelFileId>`,
      `\t<Language>${locale}</Language>`,
      `\t<RelativeUriInModelStore>${relPath}</RelativeUriInModelStore>`,
      '</AxLabelFile>',
    ].join('\n');

    fs.writeFileSync(xmlPath, xml, 'utf-8');
  }

  /**
   * Resolve a label: if plain text, create label entry and return @ref.
   * If already a label reference (@...), return as-is.
   * If useLabels is false, return the raw string.
   */
  resolve(
    model: ModelInfo,
    keyHint: string,
    text: string,
    useLabels: boolean,
  ): string {
    if (!useLabels) return text;
    if (text.startsWith('@')) return text;
    const hint = keyHint.length > 0 ? keyHint : text;
    const safeKey = this.sanitizeKey(hint);
    if (!safeKey) {
      // Cannot derive a valid label key — return the raw text rather than silently dropping it
      console.error(`[LabelManager] Cannot sanitize key hint "${hint}" — using raw text`);
      return text;
    }
    return this.upsert(model, safeKey, text);
  }
}
