import { z } from 'zod';
import { spawn } from 'child_process';
import * as fs from 'fs';
import * as path from 'path';
import { Config } from '../config';

export const BuildToolInputSchema = z.object({
  action:      z.enum(['compile', 'sync_db', 'best_practice', 'full_build', 'validate_metadata']),
  model:       z.string(),
  incremental: z.boolean().default(false),
  objects:     z.array(z.string()).optional(),
  verbose:     z.boolean().default(false),
});

export type BuildToolInput = z.infer<typeof BuildToolInputSchema>;

export async function handleBuildTool(
  input: BuildToolInput,
  config: Config,
): Promise<string> {
  switch (input.action) {
    case 'compile':
      return runCompile(input, config);
    case 'sync_db':
      return runSync(input, config);
    case 'best_practice':
      return runBestPractice(input, config);
    case 'full_build':
      return runFullBuild(input, config);
    case 'validate_metadata':
      return runValidateMetadata(input, config);
  }
}

async function runCompile(input: BuildToolInput, config: Config): Promise<string> {
  const xppc = path.join(config.binPath, 'xppc.exe');
  const binOut = path.join(config.packagesRoot, input.model, 'bin');
  // Note: no quotes around path args — xppc.exe does not handle quoted paths correctly
  const args = [
    `-metadata=${config.packagesRoot}`,
    `-modelmodule=${input.model}`,
    `-referenceFolder=${config.binPath}`,
    `-output=${binOut}`,
  ];
  if (input.incremental) args.push('-incremental');
  return runProcess(xppc, args, input.verbose ?? false, config, input.model, 'compile');
}

async function runSync(input: BuildToolInput, config: Config): Promise<string> {
  // SyncEngine.exe requires two things that are only available inside the AOS service:
  //   1. StaticMetadata/ — compiled by a full VS2022 platform build (not just xppc.exe)
  //   2. DB connection string — encrypted with the AOS service account DPAPI key
  //
  // For new models: use VS2022 → Dynamics 365 → Synchronize database
  // For re-syncing existing models after a full build: use AutoDBSync.ps1
  //
  // Attempting the call anyway in case the environment has StaticMetadata available:
  const syncExe = path.join(config.binPath, 'SyncEngine.exe');
  const webConfigPath = 'C:\\AOSService\\webroot\\web.config';
  const connStr = readConnectionString(webConfigPath);

  if (!connStr) {
    return [
      '⚠️  sync_db requires manual action in VS2022:',
      '   Dynamics 365 → Synchronize database',
      '',
      'Reason: SyncEngine.exe requires:',
      '  1. StaticMetadata/ in bin/ — only generated by a full VS2022 platform build',
      '  2. DB password — encrypted under the AOS service account, not the current user',
      '',
      `Model compiled successfully. Only the SQL table DDL sync is pending.`,
    ].join('\n');
  }

  const args = [
    `-metadatabinaries=${config.binPath}`,
    `-syncmode=partiallist`,
    `-synclist=${input.model}Table`,
    `-connect=${connStr}`,
    `-verbosity=Normal`,
  ];
  return runProcess(syncExe, args, input.verbose ?? false);
}

function readConnectionString(webConfigPath: string): string | null {
  try {
    const fs = require('fs');
    if (!fs.existsSync(webConfigPath)) return null;
    const xml = fs.readFileSync(webConfigPath, 'utf-8');
    const server = xml.match(/<add key="DataAccess\.DbServer"\s+value="([^"]+)"/)?.[1];
    const db     = xml.match(/<add key="DataAccess\.Database"\s+value="([^"]+)"/)?.[1];
    const user   = xml.match(/<add key="DataAccess\.SqlUser"\s+value="([^"]+)"/)?.[1];
    const encPwd = xml.match(/<add key="DataAccess\.SqlPwd"\s+value="([^"]+)"/)?.[1];
    if (!server || !db || !user || !encPwd) return null;
    // Password is DPAPI-encrypted under the AOS service account — cannot decrypt here.
    // Return null to trigger the manual instructions path.
    return null;
  } catch {
    return null;
  }
}

async function runBestPractice(input: BuildToolInput, config: Config): Promise<string> {
  const xppbp = path.join(config.binPath, 'xppbp.exe');
  const args = [
    `-metadata="${config.packagesRoot}"`,
    `-module=${input.model}`,
    `-model=${input.model}`,
    `-packagesRoot="${config.packagesRoot}"`,
  ];
  return runProcess(xppbp, args, input.verbose ?? false, config, input.model, 'best_practice');
}

async function runFullBuild(input: BuildToolInput, config: Config): Promise<string> {
  const compileResult  = await runCompile(input, config);
  const validateResult = await runValidateMetadata(input, config);
  const syncResult     = await runSync(input, config);
  const combined = `=== Compile ===\n${compileResult}\n\n=== Metadata Validation ===\n${validateResult}\n\n=== Sync DB ===\n${syncResult}`;
  writeBuildLog(config, input.model, 'full_build', combined);
  return combined;
}

async function runValidateMetadata(input: BuildToolInput, config: Config): Promise<string> {
  const scriptPath = path.join(__dirname, '..', '..', 'scripts', 'Validate-Metadata.ps1');
  if (!fs.existsSync(scriptPath)) {
    return `⚠️  Validate-Metadata.ps1 not found at: ${scriptPath}`;
  }
  const args = [
    '-NonInteractive',
    '-NoProfile',
    '-ExecutionPolicy', 'Bypass',
    '-File', scriptPath,
    '-PackagesRoot', config.packagesRoot,
    '-Model', input.model,
  ];
  const result = await runProcess('powershell.exe', args, input.verbose ?? false, config, input.model, 'validate_metadata');
  return result;
}

function runProcess(
  exe: string,
  args: string[],
  verbose: boolean,
  config?: Config,
  model?: string,
  action?: string,
): Promise<string> {
  return new Promise((resolve) => {
    const start = Date.now();
    const proc = spawn(exe, args, { shell: true });
    const stdout: string[] = [];
    const stderr: string[] = [];

    proc.stdout.on('data', (d: Buffer) => stdout.push(d.toString()));
    proc.stderr.on('data', (d: Buffer) => stderr.push(d.toString()));

    proc.on('close', (code) => {
      const duration = ((Date.now() - start) / 1000).toFixed(1);
      const lines = [
        `Exit code: ${code} | Duration: ${duration}s`,
        `Command: ${exe} ${args.join(' ')}`,
      ];
      if (stdout.length > 0) {
        lines.push('\n--- stdout ---');
        const out = stdout.join('');
        lines.push(verbose ? out : out.split('\n').slice(-20).join('\n'));
      }
      if (stderr.length > 0) {
        lines.push('\n--- stderr ---');
        lines.push(stderr.join(''));
      }
      const result = lines.join('\n');

      // Write full output to build log
      if (config && model && action) {
        writeBuildLog(config, model, action, result);
      }

      resolve(result);
    });

    proc.on('error', (err) => {
      resolve(`Failed to launch ${exe}: ${err.message}\nMake sure binPath is correct in config.json`);
    });
  });
}

function writeBuildLog(config: Config, model: string, action: string, content: string): void {
  try {
    const logDir = path.join(config.packagesRoot, model, 'xpp-mcp-logs');
    if (!fs.existsSync(logDir)) fs.mkdirSync(logDir, { recursive: true });
    const ts = new Date().toISOString().replace(/[:.]/g, '-').replace('T', '_').slice(0, 19);
    const logFile = path.join(logDir, `build-${action}-${ts}.log`);
    const header = [
      `Model   : ${model}`,
      `Action  : ${action}`,
      `Time    : ${new Date().toISOString()}`,
      '─'.repeat(60),
      '',
    ].join('\n');
    fs.writeFileSync(logFile, header + content, 'utf-8');
  } catch {
    // Non-fatal — log writing should never break the build
  }
}
